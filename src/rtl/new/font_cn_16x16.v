// 组合读: 码位->字形索引
//   0x80..0xA8 -> 0..40 ; 0xAE(Logo) -> 41 ; 0xB0..0xD0 -> 42..74
function [15:0] cn_rd;
    input [7:0] code_i;
    input [3:0] row_i;
    integer idx;
    begin
        if (code_i == 8'hAE)
            idx = 41 * 16 + row_i;
        else if (code_i >= 8'hB0 && code_i <= 8'hD0)
            idx = (42 + (code_i - 8'hB0)) * 16 + row_i;
        else
            idx = (code_i - 8'h80) * 16 + row_i;
        cn_rd = cn_font_rom[idx];
    end
endfunction
assign data = cn_rd(code, row);
